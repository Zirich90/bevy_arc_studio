"""Regenerate only the Studio adapter, never Quillshade output. Run after shader-editor regen."""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def catalog(root=ROOT):
    entries = []
    ids = []
    for source in sorted((root / 'crates/quillshade/src/material/materials').rglob('*.rs')):
        text = source.read_text(encoding='utf-8')
        if 'MaterialExtension2d' in text or 'impl Material2d ' in text:
            continue
        asset_id = re.search(r'pub const BAKED_ID: &str = "([^"]+)"', text)
        material = re.search(r'pub (?:type|struct) (\w+Material)\b', text)
        if not asset_id or not material:
            continue
        path = '::'.join(source.relative_to(root / 'crates/quillshade/src').with_suffix('').parts)
        entries.append(f'    crate::quillshade_bridge::register::<quillshade::{path}::{material[1]}>(app, "{asset_id[1]}");')
        ids.append(asset_id[1])
    if not entries:
        raise ValueError('No generated 3D materials found; adapter not replaced')
    output = '// Generated by scripts/quillshade_catalog.py; do not edit.\n'
    output += 'pub const MATERIAL_IDS: &[&str] = &[' + ', '.join(f'"{asset_id}"' for asset_id in ids) + '];\n'
    output += 'pub fn register(app: &mut bevy::prelude::App) {\n' + '\n'.join(entries) + '\n}\n'
    (root / 'src/quillshade_catalog.rs').write_text(output, encoding='utf-8')
    return len(entries)

if __name__ == '__main__':
    print(f'Quillshade catalog: {catalog()} 3D materials')
